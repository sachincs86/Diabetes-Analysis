def evaluate_model(model, X_train, X_test,
                   y_train, y_test,
                   title):

    model.fit(X_train, y_train)

    # Predictions
    train_pred = model.predict(X_train)
    test_pred = model.predict(X_test)

    # Probabilities for ROC
    train_prob = model.predict_proba(X_train)[:,1]
    test_prob = model.predict_proba(X_test)[:,1]

    # -----------------------------
    # Training Metrics
    # -----------------------------
    train_acc = accuracy_score(y_train, train_pred)
    train_pre = precision_score(y_train, train_pred)
    train_rec = recall_score(y_train, train_pred)
    train_f1 = f1_score(y_train, train_pred)

    # -----------------------------
    # Testing Metrics
    # -----------------------------
    test_acc = accuracy_score(y_test, test_pred)
    test_pre = precision_score(y_test, test_pred)
    test_rec = recall_score(y_test, test_pred)
    test_f1 = f1_score(y_test, test_pred)

    print("\n===================================")
    print(title)
    print("===================================")

    print("\nTraining Results")
    print(f"Accuracy  : {train_acc:.4f}")
    print(f"Precision : {train_pre:.4f}")
    print(f"Recall    : {train_rec:.4f}")
    print(f"F1 Score  : {train_f1:.4f}")

    print("\nTesting Results")
    print(f"Accuracy  : {test_acc:.4f}")
    print(f"Precision : {test_pre:.4f}")
    print(f"Recall    : {test_rec:.4f}")
    print(f"F1 Score  : {test_f1:.4f}")

    # =====================================================
    # Confusion Matrix
    # =====================================================

    cm = confusion_matrix(y_test, test_pred)

    plt.figure(figsize=(5,4))
    plt.imshow(cm, cmap='Blues')
    plt.title(title + " Confusion Matrix")
    plt.colorbar()

    plt.xticks([0,1])
    plt.yticks([0,1])

    for i in range(cm.shape[0]):
        for j in range(cm.shape[1]):
            plt.text(j,i,str(cm[i,j]),
                     ha='center',
                     va='center')

    plt.xlabel("Predicted")
    plt.ylabel("Actual")
    plt.show()

    # =====================================================
    # ROC Curve
    # =====================================================

    fpr_train, tpr_train, _ = roc_curve(y_train, train_prob)
    fpr_test, tpr_test, _ = roc_curve(y_test, test_prob)

    auc_train = auc(fpr_train, tpr_train)
    auc_test = auc(fpr_test, tpr_test)

    plt.figure(figsize=(7,5))

    plt.plot(
        fpr_train,
        tpr_train,
        label=f"Train AUC={auc_train:.3f}"
    )

    plt.plot(
        fpr_test,
        tpr_test,
        label=f"Test AUC={auc_test:.3f}"
    )

    plt.plot([0,1],[0,1],'k--')

    plt.xlabel("False Positive Rate")
    plt.ylabel("True Positive Rate")
    plt.title(title + " ROC Curve")
    plt.legend()
    plt.grid(True)

    plt.show()

